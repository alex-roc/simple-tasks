import esbuild from 'esbuild';
import process from 'process';
import { builtinModules } from 'node:module';
import { exec } from 'node:child_process';
import { readFileSync } from 'node:fs';

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === 'production';

// Plugin id comes from the manifest, so this config is reusable across plugins verbatim.
const { id: pluginId } = JSON.parse(readFileSync('manifest.json', 'utf8'));

/*
 * Reload the plugin in a running Obsidian after every successful rebuild, via the
 * official CLI (Obsidian 1.12+). OBSIDIAN_VAULT targets a different vault,
 * OBSIDIAN_RELOAD=0 turns it off.
 */
const vault = process.env.OBSIDIAN_VAULT ?? 'my-obsidian-plugins';
const obsidianBin =
	process.env.OBSIDIAN_BIN ?? '/Applications/Obsidian.app/Contents/MacOS/obsidian';
const reloadEnabled = !prod && process.env.OBSIDIAN_RELOAD !== '0';

const reloadPlugin = {
	name: 'obsidian-reload',
	setup(build) {
		build.onEnd((result) => {
			if (!reloadEnabled || result.errors.length > 0) return;
			exec(
				`"${obsidianBin}" vault="${vault}" plugin:reload id=${pluginId}`,
				(err, _stdout, stderr) => {
					if (err) {
						// Obsidian closed or plugin not enabled yet: not worth failing the build.
						console.log(`[reload] skipped: ${stderr.trim() || err.message}`);
						return;
					}
					console.log(`[reload] ${pluginId} @ ${vault}`);
				}
			);
		});
	},
};

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ['src/main.ts'],
	bundle: true,
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules,
	],
	format: 'cjs',
	target: 'es2021',
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	outfile: 'main.js',
	minify: prod,
	plugins: [reloadPlugin],
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
